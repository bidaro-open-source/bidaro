import { z } from 'zod'

export const slugSchema = z
  .string({
    required_error: 'Слаг є обов\'язковим',
    invalid_type_error: 'Слаг повинен бути рядком',
  })
  .trim()
  .toLowerCase()
  .min(3, { message: 'Слаг повинен містити щонайменше 3 символи' })
  .max(128, { message: 'Слаг не повинен перевищувати 128 символів' })
  .regex(/^[a-z0-9]+(-[a-z0-9]+)*$/, {
    message: 'Невірний формат слагу. Дозволені лише малі літери (a-z), цифри (0-9) та дефіси (-). Дефіси не можуть бути на початку, в кінці або повторюватися.',
  })
