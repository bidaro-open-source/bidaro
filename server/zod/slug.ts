import { z } from 'zod'

export const slugSchema = z
  .string({
    error: issue => issue.input === undefined
      ? 'Слаг є обов\'язковим'
      : 'Слаг повинен бути рядком',
  })
  .trim()
  .toLowerCase()
  .min(3, { error: 'Слаг повинен містити щонайменше 3 символи' })
  .max(128, { error: 'Слаг не повинен перевищувати 128 символів' })
  .regex(/^[a-z0-9]+(-[a-z0-9]+)*$/, {
    error: 'Невірний формат слагу. Дозволені лише малі літери (a-z), цифри (0-9) та дефіси (-). Дефіси не можуть бути на початку, в кінці або повторюватися.',
  })
